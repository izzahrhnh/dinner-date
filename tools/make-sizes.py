"""Writes assets/js/sizes.js: the shape (height / width) of every photo and video poster,
so the archive can be laid out before the images load. Re-run after adding photos:
    python3 tools/make-sizes.py
(New photos still work without it; they just use a typical shape until then.)"""
import glob, json, os
from PIL import Image
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = {}
for f in sorted(glob.glob(os.path.join(root, 'assets/photos/*.jpg')) + glob.glob(os.path.join(root, 'assets/videos/*.jpg'))):
    w, h = Image.open(f).size
    out[os.path.relpath(f, root)] = round(h / w, 3)
with open(os.path.join(root, 'assets/js/sizes.js'), 'w') as fh:
    fh.write('/* generated by tools/make-sizes.py */\nwindow.PHOTO_SHAPES = ' + json.dumps(out, indent=0) + ';\n')
print(len(out), 'shapes')
